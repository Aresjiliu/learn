const assert = require('assert')
const { presentDictionaryEntry, presentDictionaryDetail } = require('../services/dictionary-presentation')
assert.strictEqual(typeof presentDictionaryDetail, 'function', 'M2 detail presenter must be exported')
const meaning = '1. 卡片；\n  原始缩进与编号\n2. 票；' + '完整释义'.repeat(300)
const input = { id: 'dict:1:a', word: 'длинноеслово'.repeat(20), word_meaning_all: meaning, examples: [' пример ', null, {}, 7, 'пример', 'второй'], audioSource: 'textbook' }
const detail = presentDictionaryDetail(input)
assert.strictEqual(detail.headword, input.word)
assert.strictEqual(detail.meaningText, meaning)
assert.strictEqual(detail.wordClass, '')
assert.strictEqual(detail.hasExamples, true)
assert.deepStrictEqual(detail.exampleItems.map(item => item.text), ['пример', 'пример', 'второй'])
assert.strictEqual(new Set(detail.exampleItems.map(item => item.key)).size, 3)
assert.deepStrictEqual(presentDictionaryDetail(input).exampleItems, detail.exampleItems)
assert.strictEqual(detail.audioSource, 'textbook')
assert.deepStrictEqual(input.examples, [' пример ', null, {}, 7, 'пример', 'второй'])
assert.deepStrictEqual(presentDictionaryDetail({ examples: 'один\nдва' }).exampleItems.map(item => item.text), ['один', 'два'])
for (const invalid of [[], [null, {}, 7, '  '], {}, ' \n ', 42]) {
    const fallback = presentDictionaryDetail({ examples: invalid, sentence_all: 'Это дом.', sentences: ['Не дублировать.'], example: 'Последний.' })
    assert.deepStrictEqual(fallback.exampleItems.map(item => item.text), ['Это дом.'], 'invalid primary examples must not mask a valid alias')
    assert.strictEqual(fallback.hasExamples, true)
}
assert.deepStrictEqual(presentDictionaryDetail({ examples: [], sentence_all: {}, sentences: [null, ' Третий. '], example: 'Последний.' }).exampleItems.map(item => item.text), ['Третий.'])
assert.deepStrictEqual(presentDictionaryDetail({ examples: ['Первый.', null], sentence_all: 'Второй.' }).exampleItems.map(item => item.text), ['Первый.'])
assert.deepStrictEqual(presentDictionaryDetail({ examples: {}, sentence_all: [], sentences: [null], example: ' Последний. ' }).exampleItems.map(item => item.text), ['Последний.'])
for (const value of [undefined, null, {}, { examples: [null, 1, {}], word_character: '  ' }]) {
    const empty = presentDictionaryDetail(value)
    assert.strictEqual(empty.hasExamples, false)
    assert.strictEqual(empty.wordClass, '')
    assert.strictEqual(empty.meaningText, '释义待补充')
}
const textbook = presentDictionaryDetail({ textbookMeaning: '教材\n原文', word_meaning_all: '词典', textbookWordClass: '名', word_character: '动' })
assert.strictEqual(textbook.meaningText, '教材\n原文')
assert.strictEqual(textbook.wordClass, '名')
assert.strictEqual(presentDictionaryDetail({ textbookMeaning: '  ', translation: '译文' }).meaningText, '译文')
assert.strictEqual(presentDictionaryDetail({ meaning: '<b>原文</b>' }).meaningText, '<b>原文</b>')
assert.strictEqual(presentDictionaryEntry({ word_meaning_all: '一\n二' }).summary, '一 二', 'M1 stays unchanged')
console.log('dictionary detail presentation: PASS')
