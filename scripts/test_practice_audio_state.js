const assert = require('assert')
const fs = require('fs')

const source = fs.readFileSync('pages/exam/practice/practice.js', 'utf8')
const nextIndex = source.indexOf('nextQuestion: function')
const restartIndex = source.indexOf('restart: function')
assert.ok(nextIndex >= 0)
assert.ok(restartIndex > nextIndex)
assert.ok(source.slice(nextIndex, restartIndex).includes('audioController.stop()'))
assert.ok(source.includes('finished: true, isPlayingAudio: false'))
assert.ok(source.slice(restartIndex).includes('audioController.stop()'))
assert.ok(source.includes("audioError: '当前听力播放失败，可重试或继续作答'"))
assert.ok(source.includes('retryQuestionAudio: function'))
console.log('practice audio state tests: PASS')
