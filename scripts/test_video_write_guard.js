const assert = require('assert')
const fs = require('fs')

const source = fs.readFileSync('pages/course/video/video.js', 'utf8')
assert.ok(source.includes('!config.enableRemoteWrites || !wx.getStorageSync(\'token\')'))
const { loaded, event, records } = require('./test_video_learning_controls')
;(async () => {
    const { page, wx, requests, reads } = await loaded()
    page.onVideoPlay(event(page))
    page.onTimeUpdate(event(page, { currentTime: 30, duration: 80 }))
    assert.strictEqual(records.getPlaybackRecord(wx, 'C', 'A').record.position, 30)
    assert.deepStrictEqual(requests, [])
    assert.ok(!reads.includes('token'), 'disabled remote writes must not read credentials')
})().catch(error => { console.error(error); process.exitCode = 1 })
console.log('video write guard tests: PASS')
