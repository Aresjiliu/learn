const assert = require('assert')
const fs = require('fs')

const searchJs = fs.readFileSync('pages/dictionary/search/search.js', 'utf8')
const searchWxml = fs.readFileSync('pages/dictionary/search/search.wxml', 'utf8')
const entryWxml = fs.readFileSync('components/dictionary-entry/index.wxml', 'utf8')
const searchConfig = JSON.parse(fs.readFileSync('pages/dictionary/search/search.json', 'utf8'))
const detailJs = fs.readFileSync('pages/dictionary/detail/detail.js', 'utf8')
const detailWxml = fs.readFileSync('pages/dictionary/detail/detail.wxml', 'utf8')

assert.ok(searchJs.includes('audioPlayable: this.isAudioPlayable(word)'))
assert.ok(searchJs.includes('config.enableLocalWordAudio'))
assert.ok(searchJs.includes('/^\\/wordaudio\\/[0-9a-f]{32}\\.mp3$/'))
assert.strictEqual(searchConfig.usingComponents['dictionary-entry'], '/components/dictionary-entry/index')
assert.match(searchWxml, /<dictionary-entry[^>]*entry="\{\{item\}\}"/)
assert.ok(!/可听发音|音频待接入|教材发音|本地验证/.test(entryWxml))
assert.ok(searchWxml.includes('wx:if="{{audioDevelopmentNotice}}"'))
assert.ok(detailJs.includes('decorateWord: function'))
assert.ok(detailWxml.includes('wx:if="{{word.audioPlayable}}"'))
assert.ok(detailJs.includes('Boolean(word && word.audioPending)'))
assert.ok(detailWxml.includes('wx:if="{{word.audioPending}}"'))
assert.ok(detailWxml.includes('音频资源待接入'))
console.log('dictionary audio visibility tests: PASS')
