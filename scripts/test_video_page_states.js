const assert = require('assert')
const fs = require('fs')

const js = fs.readFileSync('pages/course/video/video.js', 'utf8')
const wxml = fs.readFileSync('pages/course/video/video.wxml', 'utf8')
assert.ok(js.includes('loading: true'))
assert.ok(js.includes("loadError: '课程媒体信息加载失败，请稍后重试'"))
assert.ok(js.includes("playbackError: ''"))
assert.ok(js.includes('retryPlayback: function'))
assert.ok(js.includes("playbackError: '当前视频无法播放，请检查媒体服务或切换其他视频'"))
assert.ok(js.includes('retryLoad: function'))
assert.ok(js.includes('const requestId = (this._loadRequestId || 0) + 1'))
assert.ok(js.includes('this._isUnloaded || requestId !== this._loadRequestId'))
assert.ok(js.includes('onUnload: function'))
assert.ok(wxml.includes('视频信息加载中'))
assert.ok(wxml.includes('wx:if="{{!loading && loadError}}"'))
assert.ok(wxml.includes('bindtap="retryLoad"'))
assert.ok(wxml.includes('bindtap="retryPlayback"'))
assert.ok(wxml.includes('currentVideo && currentVideo.url && !playbackError'))
const lockedClassMatch = wxml.match(/\{\{(\(!hasPurchased && !video\.canPreview\) \? 'locked' : '')\}\}/)
assert.ok(lockedClassMatch, 'video list item must declare its lock class condition')
const lockClass = new Function('hasPurchased', 'video', `return ${lockedClassMatch[1]}`)
assert.strictEqual(lockClass(false, { canPreview: false }), 'locked', 'unpaid non-preview videos must be locked')
assert.strictEqual(lockClass(true, { canPreview: false }), '', 'purchased non-preview videos must not be locked')
assert.ok(js.includes('const dataRequest = getCourseDetail(this.data.courseId)'))
assert.ok(/onVideoPlay: function\(\)[\s\S]*?saveRecentCourse\(wx, this\.data\.courseId\)/.test(js), 'first successful playback records recent course')
assert.ok(!js.includes("/api/courses/${this.data.courseId}/video/"))
console.log('video page state tests: PASS')
