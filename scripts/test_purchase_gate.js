const assert = require('assert')
const fs = require('fs')

const detailWxml = fs.readFileSync('pages/course/detail/detail.wxml', 'utf8')
const detailJs = fs.readFileSync('pages/course/detail/detail.js', 'utf8')
const videoWxml = fs.readFileSync('pages/course/video/video.wxml', 'utf8')
const videoJs = fs.readFileSync('pages/course/video/video.js', 'utf8')

assert.ok(!detailWxml.includes('bindtap="handleBuy"'), 'course page must not offer purchase without a payment flow')
assert.ok(!videoWxml.includes('bindtap="handlePurchase"'), 'video page must not offer purchase without a payment flow')
assert.ok(detailWxml.includes('购买暂未开放'), 'course page must explain why purchase is unavailable')
assert.ok(detailWxml.includes("contentModeLabel === '本地演示内容'") && detailWxml.includes('免费演示'), 'local sample must not present a demo price as an offer')
assert.ok(videoWxml.includes('购买暂未开放'), 'video page must explain why purchase is unavailable')
assert.ok(!detailJs.includes("/create_order/"), 'creating an order is not payment confirmation')
assert.ok(!detailJs.includes('购买成功'), 'course must not claim payment succeeded without payment confirmation')
assert.ok(!videoJs.includes('handlePurchase: function'), 'dead purchase navigation must be removed')
assert.ok(!detailJs.includes('请购买课程后观看'), 'locked course must not direct users to unavailable purchase')
assert.ok(!videoJs.includes('请购买课程后观看'), 'locked video must not direct users to unavailable purchase')
console.log('purchase gate tests: PASS')
