const assert = require('assert')
const { loaded, event, records } = require('./test_video_learning_controls')

;(async () => {
    const { page, wx } = await loaded()
    page.onVideoPlay(event(page))
    page.onTimeUpdate(event(page, { currentTime: 14.6, duration: 80 }))
    page.onVideoPause(event(page))
    assert.strictEqual(page.data.isPlaying, false)
    assert.strictEqual(records.getPlaybackRecord(wx, 'C', 'A').record.position, 14.6, 'pause preserves latest actual position before checkpoint')
    assert.strictEqual(records.getRecentPlayback(wx).record.videoId, 'A')
    page.onTimeUpdate(event(page, { currentTime: 22.8, duration: 80 }))
    page.onUnload()
    assert.strictEqual(records.getPlaybackRecord(wx, 'C', 'A').record.position, 22.8, 'leaving preserves latest visible position')
    console.log('video pause progress tests: PASS')
})().catch(error => { console.error(error); process.exitCode = 1 })
