const assert = require('assert')
const fs = require('fs')

const js = fs.readFileSync('pages/exam/list/list.js', 'utf8')
const wxml = fs.readFileSync('pages/exam/list/list.wxml', 'utf8')
assert.ok(js.includes("loadError: ''"))
assert.ok(js.includes('papers: []'))
assert.ok(js.includes('visiblePapers: []'))
assert.ok(js.includes("activeFilter: 'all'"))
assert.ok(js.includes('visiblePapers: filterPapers(allPapers, this.data.activeFilter)'))
assert.ok(js.includes('setPaperFilter: function'))
assert.ok(js.includes('visiblePapers: filterPapers(this.data.papers, filter)'))
assert.ok(js.includes('retryLoad: function'))
assert.ok(js.includes('试卷加载失败，请检查网络后重试'))
assert.ok(js.includes('const requestId = (this._loadRequestId || 0) + 1'))
assert.ok(js.includes('this._isUnloaded || requestId !== this._loadRequestId'))
assert.ok(js.includes('onUnload: function'))
assert.ok(js.includes('canPractice: item.practiceReady === true'))
assert.ok(js.includes('该试卷正在审核中'))
assert.ok(wxml.includes('{{loadError}}'))
assert.ok(wxml.includes('bindtap="retryLoad"'))
assert.ok(wxml.includes('data-can-practice="{{item.canPractice}}"'))
assert.ok(wxml.includes('内容审核中'))
assert.ok(wxml.includes("item.questionMode === 'choice' ? '选择题'"))
assert.ok(wxml.includes("item.questionMode === 'text' ? '填空题' : '题型待确认'"))
assert.ok(wxml.includes('wx:for="{{filters}}"'))
assert.ok(wxml.includes('bindtap="setPaperFilter"'))
assert.ok(wxml.includes('data-filter="{{item.value}}"'))
assert.ok(wxml.includes('wx:for="{{visiblePapers}}"'))
assert.ok(wxml.includes("papers.length ? '当前题型暂无试卷' : '暂无可练习试卷'"))
assert.ok(wxml.includes('bindtap="loadMore"'))
assert.ok(wxml.includes('bindtap="retryLoad"'))
assert.ok(wxml.includes('hasMore'))
assert.ok(wxml.includes("hasMore ? '，可继续加载后续试卷' : ''"))
assert.ok(wxml.indexOf('class="pagination"') > wxml.indexOf('wx:else class="state-card empty-state"'), 'pagination remains visible when filter has no matches')
console.log('exam list state tests: PASS')
