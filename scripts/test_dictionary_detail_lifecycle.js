const assert = require('assert')
const fs = require('fs')

const source = fs.readFileSync('pages/dictionary/detail/detail.js', 'utf8')
const unload = source.slice(source.indexOf('onUnload: function'))
assert.ok(unload.includes('audioController.stop()'))
assert.ok(unload.includes('this._isUnloaded = true'))
assert.ok(!unload.includes('this.setData'))
assert.ok(source.includes('if (!this._isUnloaded) this.setData({ isPlaying: false })'))
assert.ok(source.includes('resolveAudioUrl: function'))
assert.ok(source.includes('audioController.play(audioUrl'))
assert.ok(source.includes("音频资源待接入"))
assert.ok(source.includes('textbookMeaning'))
const onLoad = source.slice(source.indexOf('onLoad: function'), source.indexOf('showLocalWord: function'))
const apiFallback = onLoad.slice(onLoad.indexOf('}).catch(() => {'), onLoad.indexOf('            })', onLoad.indexOf('}).catch(() => {')))
assert.ok(apiFallback.includes("this.showLocalWord(query, textbookFields, '词条加载失败，请检查网络后重试')"), 'failed API fallback must preserve its error message')
assert.match(onLoad, /this\.showLocalWord\(query, textbookFields\)\s*\},\s*$/, 'offline fallback must use the default empty error')
assert.strictEqual((onLoad.match(/this\.showLocalWord\(/g) || []).length, 2, 'both local fallback paths must use the shared helper')
const showLocalWord = source.slice(source.indexOf('showLocalWord: function'), source.indexOf('resolveLocalWord: function'))
assert.ok(showLocalWord.includes("showLocalWord: function(query, textbookFields, loadError = '')"))
assert.strictEqual((showLocalWord.match(/this\.resolveLocalWord\(query, textbookFields\)/g) || []).length, 1, 'shared helper must validate local identity exactly once')
assert.strictEqual((source.match(/this\.resolveLocalWord\(/g) || []).length, 1, 'local resolution must only occur inside the shared helper')
assert.ok(showLocalWord.includes("loadError: localWord ? '' : loadError"), 'only a successful local fallback may clear the error')
assert.ok(source.includes('headword && identity(headword) === identity(query)'))
assert.ok(source.includes("if (!query.trim())"))
assert.ok(source.includes("const word = result && result.data && result.data.word"))
assert.ok(source.includes("if (!word) throw new Error('词典详情为空')"))
assert.ok(source.includes('const requestId = (this._detailRequestId || 0) + 1'))
assert.ok(source.includes('this._isUnloaded || requestId !== this._detailRequestId'))
assert.ok(unload.includes('this._detailRequestId = (this._detailRequestId || 0) + 1'))
console.log('dictionary detail lifecycle tests: PASS')
